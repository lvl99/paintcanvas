/**
 * A schema without its `@type` (which names what kind of thing it describes, e.g. `PaintCanvas/BrushConfig`), as ajv
 * only accepts keywords that are identifiers. It doesn't change validation.
 *
 * @example
 * withoutType({ $id: "x", "@type": "PaintCanvas/BrushConfig" }); // { $id: "x" }
 */
export const withoutType = <T extends object>(schema: T): Omit<T, "@type"> => {
  const copy = { ...schema };
  delete (copy as Record<string, unknown>)["@type"];
  return copy;
};

/** Keys whose values aren't schemas, or are maps of schemas, which can't be swapped for a `$ref` */
const NOT_SCHEMA_KEYS = new Set([
  "properties",
  "patternProperties",
  "$defs",
  "definitions",
  "dependentSchemas",
  "const",
  "enum",
  "default",
  "examples",
]);

/** Sub-schemas shorter than this (characters of JSON) are left in place, as a `$ref` would save little */
const MIN_SHARED_LENGTH = 200;

/**
 * Schemas with each sub-schema they use more than once (the same object, e.g. a brush parameter's settings) moved into
 * a schema of its own (`urn:paintcanvas:shared:<n>`) and `$ref`ed, so it's compiled once. Validation doesn't change;
 * the published schemas are left as they are.
 *
 * @example
 * shareRepeatedSchemas([brushPresetSchema]); // the brush preset, and its parameter settings as one shared schema
 */
export const shareRepeatedSchemas = (
  schemas: readonly object[],
  minLength = MIN_SHARED_LENGTH,
): object[] => {
  const counts = new Map<object, number>();
  const count = (node: unknown, key?: string): void => {
    if (typeof node !== "object" || node === null) return;
    if (key === undefined || !NOT_SCHEMA_KEYS.has(key))
      counts.set(node, (counts.get(node) ?? 0) + 1);
    if ((counts.get(node) ?? 0) > 1) return;
    for (const [childKey, child] of Object.entries(node))
      count(child, Array.isArray(node) ? key : childKey);
  };
  for (const schema of schemas) count(schema);
  const shared = new Map<object, string>();
  for (const [node, times] of counts)
    if (
      times > 1 &&
      !Array.isArray(node) &&
      !("$id" in node) &&
      JSON.stringify(node).length >= minLength
    )
      shared.set(node, `urn:paintcanvas:shared:${shared.size + 1}`);
  const copy = (node: unknown, key?: string, top = false): unknown => {
    if (typeof node !== "object" || node === null) return node;
    const id = shared.get(node);
    if (!top && id && (key === undefined || !NOT_SCHEMA_KEYS.has(key)))
      return { $ref: id };
    if (Array.isArray(node)) return node.map((child) => copy(child, key));
    return Object.fromEntries(
      Object.entries(node).map(([childKey, child]) => [
        childKey,
        copy(child, childKey),
      ]),
    );
  };
  return [
    ...schemas.map((schema) => copy(schema, undefined, true) as object),
    ...[...shared].map(([node, id]) => ({
      $id: id,
      ...(copy(node, undefined, true) as object),
    })),
  ];
};

/** Header added to the generated validators file */
export const GENERATED_HEADER =
  "// Generated by scripts/build-validators.ts. Do not edit; run `pnpm build:validators`.\n";

/**
 * Generate pre-compiled (standalone) ESM validator code for the asset, drawing message, document and settings schemas, so validation never compiles
 * code at runtime (no `eval`/`new Function`, allowing a strict Content Security Policy).
 *
 * @example
 * writeFileSync("validators.generated.js", generateValidatorsCode());
 */
export const generateValidatorsCode = (): string => {
  const ajv = new Ajv2020({
    strict: true,
    allErrors: false,
    // Count string length in UTF-16 code units (no runtime helper import needed); limits are about size, not characters
    unicode: false,
    // Silences the deprecation notice for the `unicode` option
    logger: false,
    // Sub-schemas used more than once are compiled once
    schemas: shareRepeatedSchemas(
      [
        assetHeaderSchema,
        brushPresetSchema,
        brushPresetCollectionSchema,
        colourPaletteSchema,
        colourPaletteCollectionSchema,
        profileGraphSchema,
        profileGraphCollectionSchema,
        strokePresetSchema,
        patchMessageSchema,
        strokeMessageSchema,
        historyMessageSchema,
        documentSchema,
        settingsSchema,
        appSettingsSchema,
      ].map(withoutType),
    ),
    // Referenced schemas are checked by their own functions, shared by every validator that uses them
    inlineRefs: false,
    code: { source: true, esm: true },
  });
  return (
    GENERATED_HEADER +
    standaloneCode(ajv, {
      validateAssetHeader: assetHeaderSchema.$id,
      validateBrushPreset: brushPresetSchema.$id,
      validateBrushPresetCollection: brushPresetCollectionSchema.$id,
      validateColourPalette: colourPaletteSchema.$id,
      validateColourPaletteCollection: colourPaletteCollectionSchema.$id,
      validateProfileGraph: profileGraphSchema.$id,
      validateProfileGraphCollection: profileGraphCollectionSchema.$id,
      validatePatchMessage: patchMessageSchema.$id,
      validateStrokeMessage: strokeMessageSchema.$id,
      validateHistoryMessage: historyMessageSchema.$id,
      validateDocument: documentSchema.$id,
      validateSettings: settingsSchema.$id,
      validateAppSettings: appSettingsSchema.$id,
    })
  );
};
