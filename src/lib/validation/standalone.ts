/**
 * A schema without its `@type` (which names what kind of thing it describes, e.g. `PaintCanvas/BrushConfig`), as ajv
 * only accepts keywords that are identifiers. It doesn't change validation.
 *
 * @example
 * withoutType({ $id: "x", "@type": "PaintCanvas/BrushConfig" }); // { $id: "x" }
 */
export const withoutType = <T extends object>(schema: T): Omit<T, "@type"> => {
  const copy = { ...schema };
  delete (copy as Record<string, unknown>)["@type"];
  return copy;
};

/** Header added to the generated validators file */
export const GENERATED_HEADER =
  "// Generated by scripts/build-validators.ts. Do not edit; run `pnpm build:validators`.\n";

/**
 * Generate pre-compiled (standalone) ESM validator code for the asset, drawing message, document and settings schemas, so validation never compiles
 * code at runtime (no `eval`/`new Function`, allowing a strict Content Security Policy).
 *
 * @example
 * writeFileSync("validators.generated.js", generateValidatorsCode());
 */
export const generateValidatorsCode = (): string => {
  const ajv = new Ajv2020({
    strict: true,
    allErrors: false,
    // Count string length in UTF-16 code units (no runtime helper import needed); limits are about size, not characters
    unicode: false,
    // Silences the deprecation notice for the `unicode` option
    logger: false,
    schemas: [
      brushPresetSchema,
      brushPresetCollectionSchema,
      colourPaletteSchema,
      colourPaletteCollectionSchema,
      profileGraphSchema,
      profileGraphCollectionSchema,
      strokePresetSchema,
      patchMessageSchema,
      strokeMessageSchema,
      historyMessageSchema,
      documentSchema,
      keyComboSchema,
      settingsSchema,
      settingsFileSchema,
    ].map(withoutType),
    code: { source: true, esm: true },
  });
  return (
    GENERATED_HEADER +
    standaloneCode(ajv, {
      validateBrushPreset: brushPresetSchema.$id,
      validateBrushPresetCollection: brushPresetCollectionSchema.$id,
      validateColourPalette: colourPaletteSchema.$id,
      validateColourPaletteCollection: colourPaletteCollectionSchema.$id,
      validateProfileGraph: profileGraphSchema.$id,
      validateProfileGraphCollection: profileGraphCollectionSchema.$id,
      validatePatchMessage: patchMessageSchema.$id,
      validateStrokeMessage: strokeMessageSchema.$id,
      validateHistoryMessage: historyMessageSchema.$id,
      validateDocument: documentSchema.$id,
      validateSettings: settingsSchema.$id,
      validateSettingsFile: settingsFileSchema.$id,
    })
  );
};
